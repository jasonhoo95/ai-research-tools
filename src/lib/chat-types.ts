import type { Descendant } from "slate";

export type ChatRole =
	| "user"
	| "assistant"
	| "model";

export interface ChatHistoryItem {
	role: ChatRole;
	content: string;
}

export interface ChatRequestBody {
	message: string;
	history?: ChatHistoryItem[];
	system?: string;
	/** Lets the backend search files uploaded earlier in this chat. */
	chatId?: string;
	/** Only search these files of the chat (e.g. the open document). */
	fileIds?: string[];
}

/** A passage from an uploaded file that an answer used. */
export interface FileReference {
	fileId: string;
	fileName: string;
	/** PDF page (1-based), when known. */
	page?: number;
	chunkIndex: number;
	/** The passage text, used to highlight it in the viewer. */
	text: string;
}

/** A document uploaded to a chat or docs workspace. */
export interface ChatFileItem {
	id: string;
	name: string;
	mimeType: string;
	sizeBytes: number;
	kind: string;
	chunkCount: number;
	messageId: string | null;
	createdAt: string;
	/** The original is stored, so it can be previewed. */
	previewable: boolean;
}

/** A file (and its pages) an answer was drawn from. */
export interface FileSource {
	fileName: string;
	pages: number[];
}

export interface ChatUsage {
	promptTokenCount?: number;
	candidatesTokenCount?: number;
	totalTokenCount?: number;
}

// ---------------------------------------------------------------------------
// Artifacts (chart / table / slide) generated by the backend on demand.
// ---------------------------------------------------------------------------

export type ArtifactKind =
	| "chart"
	| "table"
	| "slide"
	| "notesboard"
	| "notes"
	| "bio"
	| "quiz"
	| "mindmap";

export interface ChartDataPoint {
	label: string;
	value: number;
	series?: string;
}

export interface ChartArtifact {
	kind: "chart";
	title: string;
	chartType: "bar" | "line" | "donut";
	xLabel?: string;
	yLabel?: string;
	data: ChartDataPoint[];
}

export interface TableArtifact {
	kind: "table";
	title: string;
	columns: string[];
	rows: string[][];
}

export interface SlideDeckSlide {
	title: string;
	/** Legacy bullet list (used when `content` is absent). */
	bullets?: string[];
	/**
	 * Markdown body when first generated; Slate document once the slide has
	 * been edited.
	 */
	content?: string | Descendant[];
	notes?: string;
}

export interface SlideArtifact {
	kind: "slide";
	title: string;
	slides: SlideDeckSlide[];
	/** Deck theme id (see components/artifact/slide-themes); defaults to "midnight". */
	theme?: "midnight" | "paper" | "aurora";
}

export interface NotesboardNote {
	title: string;
	/**
	 * Markdown body when first created from chat; Slate document once the
	 * note has been edited on the board.
	 */
	content: string | Descendant[];
	/** Links a note back to the chat message it came from. */
	sourceMessageId?: string;
	/** Grid position / size saved after drag or resize. */
	x?: number;
	y?: number;
	w?: number;
	h?: number;
}

export interface NotesboardArtifact {
	kind: "notesboard";
	title: string;
	notes: NotesboardNote[];
	/** Board column count saved from the grid controls. */
	columnCount?: number;
}

/** Single note saved from a chat message (markdown body). */
export interface NotesArtifact {
	kind: "notes";
	title: string;
	/** Markdown — converted to Slate when rendered. */
	content: string;
	sourceMessageId?: string;
}

export type BioSectionType =
	| "about"
	| "experience"
	| "education"
	| "skills"
	| "projects"
	| "awards"
	| "other";

export interface BioSection {
	id: string;
	type: BioSectionType;
	title: string;
	/** Markdown when generated; Slate document once edited. */
	content: string | Descendant[];
}

/** LinkedIn-style profile page. */
export interface BioArtifact {
	kind: "bio";
	title: string;
	name: string;
	headline: string;
	location?: string;
	highlights: string[];
	bannerUrl?: string;
	avatarUrl?: string;
	/** Fallback banner gradient when there is no banner image. */
	palette: { from: string; to: string };
	sections: BioSection[];
}

export type QuizDifficulty = "easy" | "medium" | "hard";

export interface QuizQuestion {
	id: string;
	question: string;
	/** 2-6 answer options. */
	options: string[];
	/** Index into options of the correct answer. */
	answerIndex: number;
	/** Shown after answering. */
	explanation: string;
	difficulty: QuizDifficulty;
}

/** Multiple-choice quiz; questions are asked in array order. */
export interface QuizArtifact {
	kind: "quiz";
	title: string;
	description?: string;
	questions: QuizQuestion[];
}

export interface MindmapNode {
	id: string;
	title: string;
	/** Details shown when the node is opened. Markdown. */
	description: string;
	/** Saved canvas position; absent until laid out or moved. */
	position?: { x: number; y: number };
}

export interface MindmapEdge {
	id: string;
	/** Edges point from the earlier / parent node to the later one. */
	source: string;
	target: string;
	label?: string;
}

/** Mind map / flow of a topic; nodes are listed in sequence. */
export interface MindmapArtifact {
	kind: "mindmap";
	title: string;
	description?: string;
	nodes: MindmapNode[];
	edges: MindmapEdge[];
}

export type Artifact =
	| ChartArtifact
	| TableArtifact
	| SlideArtifact
	| NotesboardArtifact
	| NotesArtifact
	| BioArtifact
	| QuizArtifact
	| MindmapArtifact;

export interface GeneratedArtifact {
	id: string;
	createdAt: string;
	prompt: string;
	artifact: Artifact;
}

export interface CitationSource {
	title?: string;
	uri: string;
	domain?: string;
	snippet?: string;
	publishedDate?: string;
}

export type SearchProvider = "exa" | "google";

export interface ChatResponse {
	reply: string;
	model?: string;
	finishReason?: string;
	usage?: ChatUsage;
	artifact?: GeneratedArtifact;
	sources?: CitationSource[];
	searchProvider?: SearchProvider;
	/** Uploaded files whose excerpts were used to answer. */
	fileSources?: FileSource[];
	/** The passages used, best match first. */
	fileReferences?: FileReference[];
}

/** A file sent with a chat message. */
export interface MessageAttachment {
	name: string;
	/** MIME type (older messages may hold another label). */
	kind: string;
	size?: number;
}

export interface UploadedFileSummary {
	originalName: string;
	mimeType: string;
	sizeBytes: number;
	kind: "pdf" | "docx" | "image" | "video" | "text";
}

export interface FileChatResponse extends ChatResponse {
	/** First file (kept for older callers). */
	file: UploadedFileSummary;
	/** Every file sent, in order. */
	files?: UploadedFileSummary[];
	/** Whether each file was indexed so follow-up questions can search it. */
	indexed?: Array<{ name: string; chunkCount?: number; error?: string }>;
}
